-- Helper function to extract a value from the GTK configuration file
local function get_gtk_setting(key)
    local handle = io.open(os.getenv("HOME") .. "/.config/gtk-4.0/settings.ini", "r")
    if not handle then return nil end
    for line in handle:lines() do
        local found_key, value = line:match("^([%w%-]+)%s*=%s*(.-)%s*$")
        if found_key == key then
            handle:close()
            return value
        end
    end
    handle:close()
    return nil
end

-- Retrieve values dynamically generated by nwg-look
local active_cursor = get_gtk_setting("gtk-cursor-theme-name") or "BreezeX-Black"
local active_size = get_gtk_setting("gtk-cursor-theme-size") or "24"

-- Synchronize Hyprland's backend with nwg-look's current settings
hl.env("XCURSOR_THEME", active_cursor)
hl.env("XCURSOR_SIZE", active_size)
hl.env("HYPRCURSOR_THEME", active_cursor)
hl.env("HYPRCURSOR_SIZE", active_size)


